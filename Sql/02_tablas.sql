DECLARE
  l_schema VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
  l_n      NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_n FROM all_tables WHERE owner = l_schema;
  DBMS_OUTPUT.PUT_LINE('Tablas creadas: ' || l_n || ' (esperado 31)');
  IF l_n <> 31 THEN
    RAISE_APPLICATION_ERROR(-20999, '02_tablas: se esperaban 31 tablas y hay ' || l_n);
  END IF;
  SELECT COUNT(*) INTO l_n FROM all_indexes
   WHERE owner = l_schema AND (index_name LIKE 'IX\_%' ESCAPE '\' OR index_name LIKE 'UX\_%' ESCAPE '\');
  DBMS_OUTPUT.PUT_LINE('Indices ix_/ux_ creados: ' || l_n || ' (esperado 40)');
  IF l_n <> 40 THEN
    RAISE_APPLICATION_ERROR(-20999, '02_tablas: se esperaban 40 indices ix_/ux_ y hay ' || l_n);
  END IF;
END;
