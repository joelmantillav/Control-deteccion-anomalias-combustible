  CONSTRAINT ck_usuario_app_estado CHECK (estado IN ('ACTIVO','BLOQUEADO','INACTIVO')),
  CONSTRAINT ck_usuario_app_intentos CHECK (intentos_fallidos >= 0),
  CONSTRAINT ck_usuario_app_operador CHECK (rol <> 'OPERADOR' OR id_estacion IS NOT NULL)
);

