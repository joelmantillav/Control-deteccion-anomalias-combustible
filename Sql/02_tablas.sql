-- ------------------------------------------------------------
-- 8. ALERTAS Y CALIDAD
-- ------------------------------------------------------------
-- Una alerta por cada regla incumplida en cada transaccion (aunque se repita
-- en el dia: todo es evidencia), o por estacion y periodo (conciliacion).
-- La gravedad y si bloquea se obtienen de la regla (no se duplican aqui).
-- Revision: PENDIENTE -> REVISADA con resultado CONFIRMADA (atendida) o
-- FALSO_POSITIVO (descartada).
CREATE TABLE alerta (
  id_alerta            NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_regla             NUMBER(8) NOT NULL,
  id_transaccion       NUMBER(12),
  id_estacion          NUMBER(6),
  periodo_inicio       DATE,                  -- solo alertas de estacion
  fecha_deteccion      TIMESTAMP NOT NULL,
  valor_observado      NUMBER(14,3),
  valor_umbral         NUMBER(14,3),
  descripcion          VARCHAR2(400) NOT NULL,
  estado_revision      VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
  resultado_revision   VARCHAR2(20),
  id_usuario_revision  NUMBER(6),
  fecha_revision       TIMESTAMP,
  observacion_revision VARCHAR2(400),
  CONSTRAINT pk_alerta PRIMARY KEY (id_alerta),
  CONSTRAINT fk_alerta_regla FOREIGN KEY (id_regla)
    REFERENCES regla (id_regla),
  CONSTRAINT fk_alerta_transaccion FOREIGN KEY (id_transaccion)
    REFERENCES transaccion (id_transaccion),
  CONSTRAINT fk_alerta_estacion FOREIGN KEY (id_estacion)
    REFERENCES estacion (id_estacion),
  CONSTRAINT fk_alerta_usuario FOREIGN KEY (id_usuario_revision)
    REFERENCES usuario_app (id_usuario),
  CONSTRAINT ck_alerta_estado CHECK (estado_revision IN ('PENDIENTE','REVISADA')),
  CONSTRAINT ck_alerta_resultado
    CHECK (resultado_revision IS NULL OR resultado_revision IN ('CONFIRMADA','FALSO_POSITIVO')),
  -- De transaccion, o de estacion con su periodo
  CONSTRAINT ck_alerta_referencia CHECK (
    (id_transaccion IS NOT NULL AND id_estacion IS NULL AND periodo_inicio IS NULL)
    OR (id_transaccion IS NULL AND id_estacion IS NOT NULL AND periodo_inicio IS NOT NULL)),
  -- Pendiente: sin datos de revision. Revisada: con resultado, quien y cuando.
  CONSTRAINT ck_alerta_revision CHECK (
    (estado_revision = 'PENDIENTE' AND resultado_revision IS NULL
       AND id_usuario_revision IS NULL AND fecha_revision IS NULL)
    OR (estado_revision = 'REVISADA' AND resultado_revision IS NOT NULL
       AND id_usuario_revision IS NOT NULL AND fecha_revision IS NOT NULL))
);

-- Sin duplicados al reevaluar: una alerta por (regla, transaccion) y por
-- (regla, estacion, periodo).
CREATE UNIQUE INDEX ux_alerta_transaccion ON alerta (
  CASE WHEN id_transaccion IS NOT NULL THEN id_regla END,
  CASE WHEN id_transaccion IS NOT NULL THEN id_transaccion END);
CREATE UNIQUE INDEX ux_alerta_estacion ON alerta (
  CASE WHEN id_transaccion IS NULL THEN id_regla END,
  CASE WHEN id_transaccion IS NULL THEN id_estacion END,
  CASE WHEN id_transaccion IS NULL THEN periodo_inicio END);

-- Reclamos de calidad (posible adulteracion). id_recepcion identifica el
-- lote YPFB cuando se conoce; debe ser de la misma estacion y combustible
-- (lo controla un trigger).
CREATE TABLE reclamo_calidad (
  id_reclamo      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_estacion     NUMBER(6) NOT NULL,
  id_combustible  NUMBER(3) NOT NULL,
  id_recepcion    NUMBER(10),
  id_persona      NUMBER(10),
  fecha_hora      TIMESTAMP NOT NULL,
  tipo_reclamo    VARCHAR2(20) NOT NULL,
  descripcion     VARCHAR2(400) NOT NULL,
  estado          VARCHAR2(12) DEFAULT 'ABIERTO' NOT NULL,
  resultado       VARCHAR2(12),
  CONSTRAINT pk_reclamo_calidad PRIMARY KEY (id_reclamo),
  CONSTRAINT fk_reclamo_estacion FOREIGN KEY (id_estacion)
    REFERENCES estacion (id_estacion),
  CONSTRAINT fk_reclamo_combustible FOREIGN KEY (id_combustible)
    REFERENCES combustible (id_combustible),
  CONSTRAINT fk_reclamo_recepcion FOREIGN KEY (id_recepcion)
    REFERENCES recepcion_combustible (id_recepcion),
  CONSTRAINT fk_reclamo_persona FOREIGN KEY (id_persona)
    REFERENCES persona (id_persona),
  CONSTRAINT ck_reclamo_tipo CHECK (tipo_reclamo IN
    ('ADULTERACION','CONTAMINACION','VOLUMEN_INCOMPLETO','OTRO')),
  CONSTRAINT ck_reclamo_estado CHECK (estado IN ('ABIERTO','EN_ANALISIS','CERRADO')),
  CONSTRAINT ck_reclamo_resultado CHECK (
    (estado <> 'CERRADO' AND resultado IS NULL)
    OR (estado = 'CERRADO' AND resultado IN ('CONFIRMADO','DESCARTADO')))
);

