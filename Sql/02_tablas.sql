-- ============================================================
-- 02_tablas.sql
-- Modelo E-R v1 - Control de combustibles (Oracle 26ai Free)
-- RUAT, Aduana, YPFB y ANH se representan como tablas con
-- datos simulados.
-- Las tablas se crean en el orden que exigen las claves foraneas
-- ============================================================
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = combustible;

-- ------------------------------------------------------------
-- UBICACION Y ESTACIONES
-- ------------------------------------------------------------
CREATE TABLE departamento (
  id_departamento  NUMBER(2) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre           VARCHAR2(50) NOT NULL,
  CONSTRAINT pk_departamento PRIMARY KEY (id_departamento),
  CONSTRAINT uq_departamento_nombre UNIQUE (nombre)
);

CREATE TABLE municipio (
  id_municipio     NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_departamento  NUMBER(2) NOT NULL,
  nombre           VARCHAR2(100) NOT NULL,
  CONSTRAINT pk_municipio PRIMARY KEY (id_municipio),
  CONSTRAINT fk_municipio_departamento FOREIGN KEY (id_departamento)
    REFERENCES departamento (id_departamento)
);

CREATE TABLE estacion (
  id_estacion   NUMBER(6) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_municipio  NUMBER(5) NOT NULL,
  nombre        VARCHAR2(150) NOT NULL,
  nit           VARCHAR2(20) NOT NULL,
  direccion     VARCHAR2(250),
  latitud       NUMBER(9,6) NOT NULL,
  longitud      NUMBER(9,6) NOT NULL,
  es_fronteriza CHAR(1) DEFAULT 'N' NOT NULL,
  CONSTRAINT pk_estacion PRIMARY KEY (id_estacion),
  CONSTRAINT uq_estacion_nit UNIQUE (nit),
  CONSTRAINT fk_estacion_municipio FOREIGN KEY (id_municipio)
    REFERENCES municipio (id_municipio),
  CONSTRAINT ck_estacion_fronteriza CHECK (es_fronteriza IN ('S','N')),
  CONSTRAINT ck_estacion_latitud    CHECK (latitud  BETWEEN -90  AND 90),
  CONSTRAINT ck_estacion_longitud   CHECK (longitud BETWEEN -180 AND 180)
);

CREATE TABLE surtidor (
  id_surtidor  NUMBER(8) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_estacion  NUMBER(6) NOT NULL,
  codigo       VARCHAR2(20) NOT NULL,
  estado       VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT pk_surtidor PRIMARY KEY (id_surtidor),
  CONSTRAINT uq_surtidor_estacion_codigo UNIQUE (id_estacion, codigo),
  CONSTRAINT fk_surtidor_estacion FOREIGN KEY (id_estacion)
    REFERENCES estacion (id_estacion),
  CONSTRAINT ck_surtidor_estado CHECK (estado IN ('ACTIVO','INACTIVO'))
);

-- Tiempo simulado de viaje (tipo Google Maps). Origen distinto de destino.
CREATE TABLE tiempo_viaje (
  id_estacion_origen   NUMBER(6) NOT NULL,
  id_estacion_destino  NUMBER(6) NOT NULL,
  minutos_estimados    NUMBER(5) NOT NULL,
  fecha_estimacion     DATE NOT NULL,
  CONSTRAINT pk_tiempo_viaje PRIMARY KEY (id_estacion_origen, id_estacion_destino),
  CONSTRAINT fk_tviaje_origen  FOREIGN KEY (id_estacion_origen)
    REFERENCES estacion (id_estacion),
  CONSTRAINT fk_tviaje_destino FOREIGN KEY (id_estacion_destino)
    REFERENCES estacion (id_estacion),
  CONSTRAINT ck_tviaje_distintos CHECK (id_estacion_origen <> id_estacion_destino),
  CONSTRAINT ck_tviaje_minutos   CHECK (minutos_estimados > 0)
);

-- ------------------------------------------------------------
-- COMBUSTIBLES Y PRECIOS
-- ------------------------------------------------------------
CREATE TABLE unidad_medida (
  id_unidad  NUMBER(2) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre     VARCHAR2(30) NOT NULL,
  simbolo    VARCHAR2(5) NOT NULL,   -- L, m3
  CONSTRAINT pk_unidad_medida PRIMARY KEY (id_unidad),
  CONSTRAINT uq_unidad_simbolo UNIQUE (simbolo)
);

CREATE TABLE combustible (
  id_combustible  NUMBER(3) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_unidad       NUMBER(2) NOT NULL,
  nombre          VARCHAR2(50) NOT NULL,
  CONSTRAINT pk_combustible PRIMARY KEY (id_combustible),
  CONSTRAINT uq_combustible_nombre UNIQUE (nombre),
  CONSTRAINT fk_combustible_unidad FOREIGN KEY (id_unidad)
    REFERENCES unidad_medida (id_unidad)
);

-- Despachos de YPFB a la estacion, para conciliar recibido vs vendido
CREATE TABLE recepcion_combustible (
  id_recepcion    NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_estacion     NUMBER(6) NOT NULL,
  id_combustible  NUMBER(3) NOT NULL,
  nro_guia_ypfb   VARCHAR2(30) NOT NULL,
  cantidad        NUMBER(12,3) NOT NULL,
  fecha_hora      TIMESTAMP NOT NULL,
  CONSTRAINT pk_recepcion PRIMARY KEY (id_recepcion),
  CONSTRAINT uq_recepcion_guia UNIQUE (nro_guia_ypfb),
  CONSTRAINT fk_recepcion_estacion FOREIGN KEY (id_estacion)
    REFERENCES estacion (id_estacion),
  CONSTRAINT fk_recepcion_combustible FOREIGN KEY (id_combustible)
    REFERENCES combustible (id_combustible),
  CONSTRAINT ck_recepcion_cantidad CHECK (cantidad > 0)
);

-- Un combustible esta subvencionado en una fecha si existe un precio
-- SUBVENCIONADO vigente en esa fecha.
CREATE TABLE precio_combustible (
  id_precio        NUMBER(8) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_combustible   NUMBER(3) NOT NULL,
  tipo_precio      VARCHAR2(15) NOT NULL,
  precio_unitario  NUMBER(10,4) NOT NULL,
  fecha_inicio     DATE NOT NULL,
  fecha_fin        DATE,
  CONSTRAINT pk_precio PRIMARY KEY (id_precio),
  CONSTRAINT fk_precio_combustible FOREIGN KEY (id_combustible)
    REFERENCES combustible (id_combustible),
  CONSTRAINT ck_precio_tipo   CHECK (tipo_precio IN ('SUBVENCIONADO','INTERNACIONAL')),
  CONSTRAINT ck_precio_monto  CHECK (precio_unitario >= 0),
  CONSTRAINT ck_precio_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- ------------------------------------------------------------
-- VEHICULOS
-- ------------------------------------------------------------
CREATE TABLE tipo_vehiculo (
  id_tipo_vehiculo  NUMBER(2) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre            VARCHAR2(30) NOT NULL,   -- MOTO/AUTO/PESADO
  descripcion       VARCHAR2(200),
  CONSTRAINT pk_tipo_vehiculo PRIMARY KEY (id_tipo_vehiculo),
  CONSTRAINT uq_tipo_vehiculo_nombre UNIQUE (nombre)
);

-- Unica fuente de los datos tecnicos del vehiculo
CREATE TABLE ficha_aduana (
  id_ficha              NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nro_chasis            VARCHAR2(30) NOT NULL,
  nro_dui               VARCHAR2(30),
  id_tipo_vehiculo      NUMBER(2) NOT NULL,
  id_combustible        NUMBER(3) NOT NULL,
  marca                 VARCHAR2(50) NOT NULL,
  modelo                VARCHAR2(50) NOT NULL,
  anio_fabricacion      NUMBER(4) NOT NULL,
  cilindrada            NUMBER(6),
  capacidad_tanque      NUMBER(8,2) NOT NULL,   -- en la unidad del combustible
  pais_procedencia      VARCHAR2(50),
  fecha_nacionalizacion DATE,
  CONSTRAINT pk_ficha_aduana PRIMARY KEY (id_ficha),
  CONSTRAINT uq_ficha_chasis UNIQUE (nro_chasis),
  CONSTRAINT fk_ficha_tipo_vehiculo FOREIGN KEY (id_tipo_vehiculo)
    REFERENCES tipo_vehiculo (id_tipo_vehiculo),
  CONSTRAINT fk_ficha_combustible FOREIGN KEY (id_combustible)
    REFERENCES combustible (id_combustible),
  CONSTRAINT ck_ficha_anio   CHECK (anio_fabricacion >= 1900),
  CONSTRAINT ck_ficha_tanque CHECK (capacidad_tanque > 0)
);

CREATE TABLE vehiculo (
  id_vehiculo    NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_ficha       NUMBER(10),                  -- nulo si es extranjero
  placa          VARCHAR2(15) NOT NULL,
  pais_placa     VARCHAR2(3) DEFAULT 'BOL' NOT NULL,
  codigo_rfid    VARCHAR2(40),                -- B-SISA simulado; nulo si es extranjero
  fecha_registro DATE NOT NULL,
  CONSTRAINT pk_vehiculo PRIMARY KEY (id_vehiculo),
  CONSTRAINT uq_vehiculo_ficha UNIQUE (id_ficha),
  CONSTRAINT uq_vehiculo_rfid  UNIQUE (codigo_rfid),
  CONSTRAINT uq_vehiculo_placa UNIQUE (placa, pais_placa),
  CONSTRAINT fk_vehiculo_ficha FOREIGN KEY (id_ficha)
    REFERENCES ficha_aduana (id_ficha)
);

-- ------------------------------------------------------------
-- PERSONAS
-- ------------------------------------------------------------
CREATE TABLE persona (
  id_persona        NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  tipo_documento    VARCHAR2(10) NOT NULL,   -- CI/PASAPORTE
  nro_documento     VARCHAR2(20) NOT NULL,
  complemento       VARCHAR2(5),
  nombres           VARCHAR2(100) NOT NULL,
  apellido_paterno  VARCHAR2(60),
  apellido_materno  VARCHAR2(60),
  nacionalidad      VARCHAR2(50) NOT NULL,
  fecha_registro    DATE NOT NULL,
  CONSTRAINT pk_persona PRIMARY KEY (id_persona),
  CONSTRAINT uq_persona_documento UNIQUE (tipo_documento, nro_documento, complemento),
  CONSTRAINT ck_persona_tipo_doc CHECK (tipo_documento IN ('CI','PASAPORTE'))
);

CREATE TABLE huella_digital (
  id_huella          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_persona         NUMBER(10) NOT NULL,
  plantilla          BLOB NOT NULL,
  fecha_enrolamiento DATE NOT NULL,
  estado             VARCHAR2(15) DEFAULT 'ACTIVA' NOT NULL,
  CONSTRAINT pk_huella PRIMARY KEY (id_huella),
  CONSTRAINT uq_huella_persona UNIQUE (id_persona),
  CONSTRAINT fk_huella_persona FOREIGN KEY (id_persona)
    REFERENCES persona (id_persona),
  -- Valores de estado supuestos: el modelo solo define el default 'ACTIVA'
  CONSTRAINT ck_huella_estado CHECK (estado IN ('ACTIVA','INACTIVA'))
);

CREATE TABLE registro_ruat (
  id_ruat      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_vehiculo  NUMBER(10) NOT NULL,
  id_persona   NUMBER(10) NOT NULL,           -- propietario
  clase        VARCHAR2(30) NOT NULL,
  servicio     VARCHAR2(20) NOT NULL,         -- PARTICULAR
  fecha_alta   DATE NOT NULL,
  fecha_baja   DATE,
  CONSTRAINT pk_registro_ruat PRIMARY KEY (id_ruat),
  CONSTRAINT fk_ruat_vehiculo FOREIGN KEY (id_vehiculo)
    REFERENCES vehiculo (id_vehiculo),
  CONSTRAINT fk_ruat_persona FOREIGN KEY (id_persona)
    REFERENCES persona (id_persona),
  CONSTRAINT ck_ruat_fechas CHECK (fecha_baja IS NULL OR fecha_baja >= fecha_alta)
);

-- ------------------------------------------------------------
-- REGLAS DINAMICAS (versionadas por vigencia)
-- ------------------------------------------------------------
CREATE TABLE tipo_periodo (
  id_tipo_periodo  NUMBER(2) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  codigo           VARCHAR2(10) NOT NULL,    -- DIA/SEMANA/MES
  nombre           VARCHAR2(30) NOT NULL,
  CONSTRAINT pk_tipo_periodo PRIMARY KEY (id_tipo_periodo),
  CONSTRAINT uq_tipo_periodo_codigo UNIQUE (codigo),
  CONSTRAINT ck_tipo_periodo_codigo CHECK (codigo IN ('DIA','SEMANA','MES'))
);

CREATE TABLE tipo_regla (
  id_tipo_regla  NUMBER(4) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  codigo         VARCHAR2(40) NOT NULL,
  nombre         VARCHAR2(100) NOT NULL,
  familia        VARCHAR2(15) NOT NULL,
  descripcion    VARCHAR2(400),
  CONSTRAINT pk_tipo_regla PRIMARY KEY (id_tipo_regla),
  CONSTRAINT uq_tipo_regla_codigo UNIQUE (codigo),
  CONSTRAINT ck_tipo_regla_familia
    CHECK (familia IN ('PRECIO','REGISTRO','OPERATIVA','ANOMALIA'))
);

-- Cada fila es una version de una regla. Al cambiar la politica se cierra
-- la vigencia (fecha_fin) y se crea otra fila.
CREATE TABLE regla (
  id_regla          NUMBER(8) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_tipo_regla     NUMBER(4) NOT NULL,
  id_tipo_vehiculo  NUMBER(2),               -- ambito opcional
  id_combustible    NUMBER(3),               -- ambito opcional
  id_tipo_periodo   NUMBER(2),
  solo_fronteriza   CHAR(1),                 -- S/N, opcional
  valor             NUMBER(12,3),
  valor_secundario  NUMBER(12,3),
  gravedad          VARCHAR2(5),             -- solo familia ANOMALIA
  fecha_inicio      DATE NOT NULL,
  fecha_fin         DATE,
  CONSTRAINT pk_regla PRIMARY KEY (id_regla),
  CONSTRAINT fk_regla_tipo_regla FOREIGN KEY (id_tipo_regla)
    REFERENCES tipo_regla (id_tipo_regla),
  CONSTRAINT fk_regla_tipo_vehiculo FOREIGN KEY (id_tipo_vehiculo)
    REFERENCES tipo_vehiculo (id_tipo_vehiculo),
  CONSTRAINT fk_regla_combustible FOREIGN KEY (id_combustible)
    REFERENCES combustible (id_combustible),
  CONSTRAINT fk_regla_tipo_periodo FOREIGN KEY (id_tipo_periodo)
    REFERENCES tipo_periodo (id_tipo_periodo),
  CONSTRAINT ck_regla_fronteriza CHECK (solo_fronteriza IS NULL OR solo_fronteriza IN ('S','N')),
  CONSTRAINT ck_regla_gravedad   CHECK (gravedad IS NULL OR gravedad IN ('BAJA','MEDIA','ALTA')),
  CONSTRAINT ck_regla_fechas     CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- Vincula el vehiculo con la huella de su propietario RUAT.
-- id_regla = version de MAX_VEHICULOS_PERSONA aplicada.
CREATE TABLE registro_beneficio (
  id_beneficio  NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_vehiculo   NUMBER(10) NOT NULL,
  id_persona    NUMBER(10) NOT NULL,
  id_regla      NUMBER(8) NOT NULL,
  fecha_inicio  DATE NOT NULL,
  fecha_fin     DATE,
  CONSTRAINT pk_registro_beneficio PRIMARY KEY (id_beneficio),
  CONSTRAINT fk_beneficio_vehiculo FOREIGN KEY (id_vehiculo)
    REFERENCES vehiculo (id_vehiculo),
  CONSTRAINT fk_beneficio_persona FOREIGN KEY (id_persona)
    REFERENCES persona (id_persona),
  CONSTRAINT fk_beneficio_regla FOREIGN KEY (id_regla)
    REFERENCES regla (id_regla),
  CONSTRAINT ck_beneficio_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- Un solo beneficio vigente (fecha_fin nula) por vehiculo
CREATE UNIQUE INDEX ux_beneficio_vigente
  ON registro_beneficio (CASE WHEN fecha_fin IS NULL THEN id_vehiculo END);

-- ------------------------------------------------------------
-- OPERACIONES Y ALERTAS
-- ------------------------------------------------------------
CREATE TABLE permiso_bidon (
  id_permiso          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_persona          NUMBER(10) NOT NULL,
  id_combustible      NUMBER(3) NOT NULL,
  id_tipo_periodo     NUMBER(2) NOT NULL,
  nro_resolucion_anh  VARCHAR2(30) NOT NULL,
  motivo              VARCHAR2(200) NOT NULL,
  cantidad_autorizada NUMBER(10,3) NOT NULL,
  fecha_emision       DATE NOT NULL,
  fecha_inicio        DATE NOT NULL,
  fecha_fin           DATE NOT NULL,
  CONSTRAINT pk_permiso_bidon PRIMARY KEY (id_permiso),
  CONSTRAINT uq_permiso_resolucion UNIQUE (nro_resolucion_anh),
  CONSTRAINT fk_permiso_persona FOREIGN KEY (id_persona)
    REFERENCES persona (id_persona),
  CONSTRAINT fk_permiso_combustible FOREIGN KEY (id_combustible)
    REFERENCES combustible (id_combustible),
  CONSTRAINT fk_permiso_tipo_periodo FOREIGN KEY (id_tipo_periodo)
    REFERENCES tipo_periodo (id_tipo_periodo),
  CONSTRAINT ck_permiso_cantidad CHECK (cantidad_autorizada > 0),
  CONSTRAINT ck_permiso_fechas   CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE transaccion (
  id_transaccion    NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_surtidor       NUMBER(8) NOT NULL,
  id_combustible    NUMBER(3) NOT NULL,
  id_persona        NUMBER(10),              -- quien carga; nulo si falla la identificacion
  fecha_hora        TIMESTAMP NOT NULL,
  cantidad_total    NUMBER(10,3) NOT NULL,
  tipo_transaccion  VARCHAR2(10) NOT NULL,
  huella_verificada CHAR(1) NOT NULL,
  CONSTRAINT pk_transaccion PRIMARY KEY (id_transaccion),
  CONSTRAINT fk_transaccion_surtidor FOREIGN KEY (id_surtidor)
    REFERENCES surtidor (id_surtidor),
  CONSTRAINT fk_transaccion_combustible FOREIGN KEY (id_combustible)
    REFERENCES combustible (id_combustible),
  CONSTRAINT fk_transaccion_persona FOREIGN KEY (id_persona)
    REFERENCES persona (id_persona),
  CONSTRAINT ck_transaccion_tipo     CHECK (tipo_transaccion IN ('VEHICULAR','BIDON')),
  CONSTRAINT ck_transaccion_huella   CHECK (huella_verificada IN ('S','N')),
  CONSTRAINT ck_transaccion_cantidad CHECK (cantidad_total > 0)
);

-- Especializacion 1:1 de transaccion (tipo VEHICULAR)
CREATE TABLE carga_vehicular (
  id_transaccion  NUMBER(12) NOT NULL,
  id_vehiculo     NUMBER(10) NOT NULL,
  id_beneficio    NUMBER(10),                -- nulo si no aplica subvencion
  id_regla_cuota  NUMBER(8),                 -- version de CUOTA_SUBVENCIONADA aplicada
  rfid_leido      CHAR(1) NOT NULL,
  CONSTRAINT pk_carga_vehicular PRIMARY KEY (id_transaccion),
  CONSTRAINT fk_carga_transaccion FOREIGN KEY (id_transaccion)
    REFERENCES transaccion (id_transaccion),
  CONSTRAINT fk_carga_vehiculo FOREIGN KEY (id_vehiculo)
    REFERENCES vehiculo (id_vehiculo),
  CONSTRAINT fk_carga_beneficio FOREIGN KEY (id_beneficio)
    REFERENCES registro_beneficio (id_beneficio),
  CONSTRAINT fk_carga_regla_cuota FOREIGN KEY (id_regla_cuota)
    REFERENCES regla (id_regla),
  CONSTRAINT ck_carga_rfid CHECK (rfid_leido IN ('S','N'))
);

-- Especializacion 1:1 de transaccion (tipo BIDON)
CREATE TABLE compra_bidon (
  id_transaccion    NUMBER(12) NOT NULL,
  id_permiso        NUMBER(10),              -- nulo si compra sin permiso
  nro_recipientes   NUMBER(3) NOT NULL,
  motivo_declarado  VARCHAR2(200),
  CONSTRAINT pk_compra_bidon PRIMARY KEY (id_transaccion),
  CONSTRAINT fk_bidon_transaccion FOREIGN KEY (id_transaccion)
    REFERENCES transaccion (id_transaccion),
  CONSTRAINT fk_bidon_permiso FOREIGN KEY (id_permiso)
    REFERENCES permiso_bidon (id_permiso),
  CONSTRAINT ck_bidon_recipientes CHECK (nro_recipientes > 0)
);

CREATE TABLE detalle_transaccion (
  id_transaccion  NUMBER(12) NOT NULL,
  nro_linea       NUMBER(2) NOT NULL,
  id_precio       NUMBER(8) NOT NULL,
  cantidad        NUMBER(10,3) NOT NULL,
  motivo_precio   VARCHAR2(25) NOT NULL,
  CONSTRAINT pk_detalle_transaccion PRIMARY KEY (id_transaccion, nro_linea),
  CONSTRAINT fk_detalle_transaccion FOREIGN KEY (id_transaccion)
    REFERENCES transaccion (id_transaccion),
  CONSTRAINT fk_detalle_precio FOREIGN KEY (id_precio)
    REFERENCES precio_combustible (id_precio),
  CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_detalle_motivo CHECK (motivo_precio IN (
    'CUOTA','EXCEDE_CUOTA','NO_TITULAR','SIN_BENEFICIO','SIN_SUBVENCION',
    'EXTRANJERO','FALLA_IDENTIFICACION','SIN_PERMISO','EXCEDE_PERMISO'))
);

-- Debe referenciar una transaccion o una estacion.
-- La gravedad se obtiene de la regla.
CREATE TABLE alerta (
  id_alerta          NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_regla           NUMBER(8) NOT NULL,
  id_transaccion     NUMBER(12),
  id_estacion        NUMBER(6),
  fecha_deteccion    TIMESTAMP NOT NULL,
  descripcion        VARCHAR2(400) NOT NULL,
  estado_revision    VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
  resultado_revision VARCHAR2(20),
  fecha_revision     DATE,
  CONSTRAINT pk_alerta PRIMARY KEY (id_alerta),
  CONSTRAINT fk_alerta_regla FOREIGN KEY (id_regla)
    REFERENCES regla (id_regla),
  CONSTRAINT fk_alerta_transaccion FOREIGN KEY (id_transaccion)
    REFERENCES transaccion (id_transaccion),
  CONSTRAINT fk_alerta_estacion FOREIGN KEY (id_estacion)
    REFERENCES estacion (id_estacion),
  CONSTRAINT ck_alerta_estado CHECK (estado_revision IN ('PENDIENTE','REVISADA')),
  CONSTRAINT ck_alerta_resultado
    CHECK (resultado_revision IS NULL OR resultado_revision IN ('CONFIRMADA','FALSO_POSITIVO')),
  CONSTRAINT ck_alerta_referencia
    CHECK (id_transaccion IS NOT NULL OR id_estacion IS NOT NULL),
  -- Una alerta pendiente no tiene resultado; una revisada si
  CONSTRAINT ck_alerta_revision CHECK (
    (estado_revision = 'PENDIENTE' AND resultado_revision IS NULL)
    OR (estado_revision = 'REVISADA' AND resultado_revision IS NOT NULL))
);

-- ------------------------------------------------------------
-- INDICES para claves foraneas y consultas de deteccion
-- (Oracle no indexa las FK automaticamente)
-- ------------------------------------------------------------
CREATE INDEX ix_municipio_depto      ON municipio (id_departamento);
CREATE INDEX ix_estacion_municipio   ON estacion (id_municipio);
CREATE INDEX ix_recepcion_estacion   ON recepcion_combustible (id_estacion, id_combustible, fecha_hora);
CREATE INDEX ix_precio_vigencia      ON precio_combustible (id_combustible, tipo_precio, fecha_inicio);
CREATE INDEX ix_ruat_vehiculo        ON registro_ruat (id_vehiculo);
CREATE INDEX ix_ruat_persona         ON registro_ruat (id_persona);
CREATE INDEX ix_beneficio_vehiculo   ON registro_beneficio (id_vehiculo);
CREATE INDEX ix_beneficio_persona    ON registro_beneficio (id_persona);
CREATE INDEX ix_regla_tipo_vigencia  ON regla (id_tipo_regla, fecha_inicio, fecha_fin);
CREATE INDEX ix_permiso_persona      ON permiso_bidon (id_persona, id_combustible);
CREATE INDEX ix_transaccion_persona  ON transaccion (id_persona, fecha_hora);
CREATE INDEX ix_transaccion_surtidor ON transaccion (id_surtidor, fecha_hora);
CREATE INDEX ix_carga_vehiculo       ON carga_vehicular (id_vehiculo);
CREATE INDEX ix_alerta_regla         ON alerta (id_regla);
CREATE INDEX ix_alerta_transaccion   ON alerta (id_transaccion);
CREATE INDEX ix_alerta_estacion      ON alerta (id_estacion);
CREATE INDEX ix_alerta_estado        ON alerta (estado_revision, fecha_deteccion);
